import { RefusalError } from "../lib/exit.js";
import type {
  RegistryEntry,
  RegistryTable,
  TableImport,
  TableShape,
} from "../lib/schema.js";

// Generated tables (plan 0116, Phase 7). A registration table is a file the CLI writes in
// full on every run: the module that owns the table declares it in `tables`, and every
// module that adds a row declares it in `entries`. The file that held the table before
// imports the export and spreads it, so a remove is a render without the row and no
// codemod edits a file the owner keeps.
//
// The print is laid out the way Prettier prints it (`printWidth` 80, two spaces, double
// quotes, trailing commas where ES5 allows them), so `prettier --check` in the project
// leaves a generated file unchanged. `tables.test.ts` holds the print to Prettier itself.

/** The one header line of every generated file. */
export const GENERATED_HEADER =
  "// Generated by saasaloy. Do not edit: the CLI writes this file in full on every run.";

/** The order of an entry that names none. */
export const DEFAULT_ORDER = 1000;

const PRINT_WIDTH = 80;

/** A table as the render resolved it: its owner and the project path of its file. */
export interface ResolvedTable {
  table: RegistryTable;
  /** The module that declares the table, or `base` for the template. */
  owner: string;
  /** Project-relative POSIX path of the generated file. */
  path: string;
}

/** A row and the module that adds it. */
export interface PlacedEntry {
  module: string;
  entry: RegistryEntry;
}

/** The camelCase of a table id: `email.providers` is `emailProviders`. */
export function exportName(id: string): string {
  const [head = "", ...rest] = id.split(/[.-]/);
  return (
    head +
    rest.map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("")
  );
}

/**
 * The rows of one table in their written order: by `order`, then by module name. The
 * sort is stable, so one module's rows keep the order its descriptor lists them in.
 */
export function sortEntries(entries: readonly PlacedEntry[]): PlacedEntry[] {
  return entries.toSorted((left, right) => {
    const byOrder =
      (left.entry.order ?? DEFAULT_ORDER) -
      (right.entry.order ?? DEFAULT_ORDER);
    if (byOrder !== 0) {
      return byOrder;
    }
    return left.module < right.module ? -1 : left.module > right.module ? 1 : 0;
  });
}

/** Why a row does not fit its table's shape, or `undefined` when it fits. */
export function entryProblem(
  shape: TableShape,
  entry: RegistryEntry
): string | undefined {
  const needs = (fields: (keyof RegistryEntry)[]): string | undefined => {
    const missing = fields.filter((field) => entry[field] === undefined);
    return missing.length === 0
      ? undefined
      : `a ${shape} row needs ${missing.map((field) => `\`${field}\``).join(", ")}`;
  };
  switch (shape) {
    case "calls": {
      return needs(["call", "import"]);
    }
    case "routes": {
      return needs(["path", "call", "import"]);
    }
    case "objects": {
      return needs(["entry"]);
    }
    case "nav": {
      return (
        needs(["area", "group", "entry", "import"]) ??
        (entry.entry?.to === undefined
          ? "a nav row needs `entry.to`"
          : undefined)
      );
    }
    default: {
      const exhaustive: never = shape;
      return `unknown shape ${String(exhaustive)}`;
    }
  }
}

/** The identity two rows of one table must not share. */
function identity(shape: TableShape, entry: RegistryEntry): string {
  switch (shape) {
    case "calls": {
      return entry.call ?? "";
    }
    case "routes": {
      return entry.path ?? "";
    }
    case "nav": {
      return `${entry.area ?? ""}\0${String(entry.entry?.to)}`;
    }
    default: {
      return JSON.stringify(entry.entry);
    }
  }
}

/**
 * Print one generated file: the header, the imports every row and table needs, and one
 * export for each table, in the order `tables` lists them. A row that repeats another
 * row's identity (a call, a route path, a nav `to`) is printed once, the first in order.
 */
export function printTableFile(
  path: string,
  tables: readonly ResolvedTable[],
  entries: ReadonlyMap<string, readonly PlacedEntry[]>
): string {
  const imports = new Imports(path);
  const blocks: string[] = [];
  for (const { table } of tables) {
    const rows: RegistryEntry[] = [];
    const seen = new Set<string>();
    for (const placed of sortEntries(entries.get(table.id) ?? [])) {
      const problem = entryProblem(table.shape, placed.entry);
      if (problem !== undefined) {
        throw new RefusalError(
          `Module "${placed.module}" adds a row to table "${table.id}" that does not fit: ${problem}.`
        );
      }
      const key = identity(table.shape, placed.entry);
      if (seen.has(key)) {
        continue;
      }
      seen.add(key);
      rows.push(placed.entry);
      if (placed.entry.import !== undefined) {
        imports.add(placed.entry.import, false);
      }
    }
    if (table.type !== undefined) {
      imports.add(table.type, true);
    }
    if (table.shape === "routes") {
      for (const name of ["Env", "Hono", "Schema"]) {
        imports.add({ from: "hono", name }, true);
      }
    }
    blocks.push(printTable(table, rows));
  }
  for (const { table } of tables) {
    imports.reserve(exportName(table.id));
  }
  const head = [GENERATED_HEADER, ...imports.print()].join("\n");
  return `${head}\n\n${blocks.join("\n\n")}\n`;
}

function printTable(table: RegistryTable, rows: RegistryEntry[]): string {
  const name = exportName(table.id);
  switch (table.shape) {
    case "calls": {
      return printArray(
        `export const ${name} = `,
        rows.map((row) => `${row.call ?? ""}()`),
        ";",
        false
      );
    }
    case "objects": {
      const type = table.type === undefined ? "" : `: ${table.type.name}[]`;
      return printObjects(
        `export const ${name}${type} = `,
        rows.map((row) => properties(row.entry ?? {})),
        ";"
      );
    }
    case "nav": {
      return printObjects(
        `export const ${name} = `,
        rows.map((row) => [
          `area: ${printString(row.area ?? "")}`,
          `group: ${printString(row.group ?? "")}`,
          ...properties(row.entry ?? {}),
          `icon: ${row.import?.name ?? ""}`,
        ]),
        " as const;"
      );
    }
    case "routes": {
      return printRoutes(
        name,
        rows.map(
          (row) => `.route(${printString(row.path ?? "")}, ${row.call ?? ""})`
        )
      );
    }
    default: {
      const exhaustive: never = table.shape;
      throw new Error(`unknown table shape ${String(exhaustive)}`);
    }
  }
}

function properties(entry: Record<string, unknown>): string[] {
  return Object.entries(entry).map(
    ([key, value]) => `${printKey(key)}: ${printValue(value)}`
  );
}

/** A property key, quoted only where Prettier's `as-needed` keeps quotes. */
function printKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : printString(key);
}

/** A JSON value as TypeScript source, nested objects and arrays on one line. */
function printValue(value: unknown): string {
  if (typeof value === "string") {
    return printString(value);
  }
  if (value === null || typeof value === "boolean") {
    return String(value);
  }
  if (typeof value === "number" && Number.isFinite(value)) {
    return String(value);
  }
  if (Array.isArray(value)) {
    return `[${value.map(printValue).join(", ")}]`;
  }
  if (typeof value === "object") {
    const props = properties(value as Record<string, unknown>);
    return props.length === 0 ? "{}" : `{ ${props.join(", ")} }`;
  }
  throw new TypeError("a table row holds JSON values only");
}

/**
 * A string literal in the quotes Prettier picks: double quotes, unless the text holds
 * more double quotes than single ones.
 */
export function printString(value: string): string {
  const doubles = value.split('"').length - 1;
  const singles = value.split("'").length - 1;
  const json = JSON.stringify(value);
  if (doubles <= singles) {
    return json;
  }
  const inner = json
    .slice(1, -1)
    .replaceAll(String.raw`\"`, '"')
    .replaceAll("'", String.raw`\'`);
  return `'${inner}'`;
}

/** `[a, b]` on one line when it fits, else one element on each line. */
function printArray(
  lead: string,
  elements: string[],
  tail: string,
  forceBreak: boolean
): string {
  if (elements.length === 0) {
    return `${lead}[]${tail}`;
  }
  const oneLine = `${lead}[${elements.join(", ")}]${tail}`;
  if (!forceBreak && fits(oneLine) && !oneLine.includes("\n")) {
    return oneLine;
  }
  return `${lead}[\n${elements.map((element) => `${indent(element)},`).join("\n")}\n]${tail}`;
}

/**
 * An array of object literals. Prettier breaks such an array when it holds more than one
 * object and every object has more than one property; otherwise it breaks it only when it
 * does not fit. An object prints on one line when it fits there, else one property on
 * each line.
 */
function printObjects(lead: string, rows: string[][], tail: string): string {
  const flat = rows.map((props) => `{ ${props.join(", ")} }`);
  const forceBreak = rows.length > 1 && rows.every((props) => props.length > 1);
  const oneLine = `${lead}[${flat.join(", ")}]${tail}`;
  if (rows.length === 0 || (!forceBreak && fits(oneLine))) {
    return rows.length === 0 ? `${lead}[]${tail}` : oneLine;
  }
  const printed = rows.map((props, index) => {
    const line = `  ${flat[index] ?? ""},`;
    if (fits(line)) {
      return line;
    }
    return `  {\n${props.map((prop) => `    ${prop},`).join("\n")}\n  },`;
  });
  return `${lead}[\n${printed.join("\n")}\n]${tail}`;
}

/** The route chain: a function that takes the app and returns it with every link. */
function printRoutes(name: string, links: string[]): string {
  const params = "<E extends Env, S extends Schema, B extends string>";
  const arg = "app: Hono<E, S, B>";
  const one = `export function ${name}${params}(${arg}) {`;
  let signature: string;
  if (fits(one)) {
    signature = one;
  } else if (fits(`export function ${name}${params}(`)) {
    signature = `export function ${name}${params}(\n  ${arg}\n) {`;
  } else {
    signature = `export function ${name}<\n  E extends Env,\n  S extends Schema,\n  B extends string,\n>(${arg}) {`;
  }
  const oneLine = `  return app${links.join("")};`;
  const body =
    links.length === 0 || fits(oneLine)
      ? oneLine
      : `  return app\n${links.map((link) => `    ${link}`).join("\n")};`;
  return `${signature}\n${body}\n}`;
}

function fits(line: string): boolean {
  return line.split("\n").every((part) => part.length <= PRINT_WIDTH);
}

function indent(text: string): string {
  return text
    .split("\n")
    .map((line) => (line === "" ? line : `  ${line}`))
    .join("\n");
}

/** The import lines of one generated file, grouped by specifier. */
class Imports {
  private readonly file: string;
  private readonly values = new Map<string, Set<string>>();
  private readonly types = new Map<string, Set<string>>();
  /** Each local name and the specifier it binds, so one name binds one thing. */
  private readonly bound = new Map<string, string>();

  constructor(file: string) {
    this.file = file;
  }

  add(spec: TableImport, typeOnly: boolean): void {
    const held = this.bound.get(spec.name);
    if (held !== undefined && held !== spec.from) {
      throw new RefusalError(
        `Two rows of ${this.file} import "${spec.name}", one from ${held} and one from ${spec.from}. Rename one of the imports.`
      );
    }
    this.bound.set(spec.name, spec.from);
    const map = typeOnly ? this.types : this.values;
    map.set(spec.from, (map.get(spec.from) ?? new Set()).add(spec.name));
  }

  /** An export name of the file, which no import may take. */
  reserve(name: string): void {
    if (this.bound.has(name)) {
      throw new RefusalError(
        `${this.file} exports "${name}", and a row imports a binding of that name. Rename the import.`
      );
    }
  }

  /** Package specifiers first, then relative ones; a type import before a value import. */
  print(): string[] {
    const lines: { rank: string; text: string }[] = [];
    const emit = (map: Map<string, Set<string>>, typeOnly: boolean): void => {
      for (const [from, names] of map) {
        const sorted = [...names].toSorted(byCodePoint);
        const lead = typeOnly ? "import type " : "import ";
        const tail = ` from ${JSON.stringify(from)};`;
        const oneLine = `${lead}{ ${sorted.join(", ")} }${tail}`;
        const text = fits(oneLine)
          ? oneLine
          : `${lead}{\n${sorted.map((name) => `  ${name},`).join("\n")}\n}${tail}`;
        const relative = from.startsWith(".") ? "1" : "0";
        lines.push({
          rank: `${relative}${from}\0${typeOnly ? "0" : "1"}`,
          text,
        });
      }
    };
    emit(this.types, true);
    emit(this.values, false);
    return lines
      .toSorted((left, right) => byCodePoint(left.rank, right.rank))
      .map((line) => line.text);
  }
}

function byCodePoint(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

/** The tables of a render and the rows of every module, before the print. */
export interface TableSources {
  /** Each module that owns tables, `base` first, then the set in the fixed order. */
  owners: readonly { module: string; tables: readonly RegistryTable[] }[];
  /** Each module's rows whose `when` holds, in the fixed order. */
  rows: readonly { module: string; entries: readonly RegistryEntry[] }[];
  /** The project path of a table's `file`, aliases resolved. */
  resolve: (file: string) => string;
}

export interface RenderedTables {
  /** Each generated file: its path, the module that owns it and its content. */
  files: { path: string; owner: string; content: string }[];
  /** A row whose table no module of the set owns. */
  warnings: string[];
}

/** Print every generated file of a render. Two tables with one id refuse. */
export function renderTables(sources: TableSources): RenderedTables {
  const byId = new Map<string, ResolvedTable>();
  for (const { module, tables } of sources.owners) {
    for (const table of tables) {
      const held = byId.get(table.id);
      if (held !== undefined) {
        throw new RefusalError(
          `Modules "${held.owner}" and "${module}" both declare table "${table.id}". A table has one owner.`
        );
      }
      byId.set(table.id, {
        owner: module,
        path: sources.resolve(table.file),
        table,
      });
    }
  }
  const entries = new Map<string, PlacedEntry[]>();
  const warnings: string[] = [];
  for (const { module, entries: list } of sources.rows) {
    for (const entry of list) {
      if (!byId.has(entry.table)) {
        warnings.push(
          `${module}: row for table ${entry.table} not written — no module in the set owns that table.`
        );
        continue;
      }
      entries.set(entry.table, [
        ...(entries.get(entry.table) ?? []),
        { entry, module },
      ]);
    }
  }
  const byFile = new Map<string, ResolvedTable[]>();
  for (const resolved of byId.values()) {
    byFile.set(resolved.path, [...(byFile.get(resolved.path) ?? []), resolved]);
  }
  const files: RenderedTables["files"] = [];
  for (const [path, tables] of byFile) {
    const owners = new Set(tables.map((table) => table.owner));
    if (owners.size > 1) {
      throw new RefusalError(
        `${path} holds tables of ${[...owners].join(" and ")}. A generated file has one owner.`
      );
    }
    files.push({
      content: printTableFile(path, tables, entries),
      owner: tables[0]?.owner ?? "",
      path,
    });
  }
  return { files, warnings };
}
