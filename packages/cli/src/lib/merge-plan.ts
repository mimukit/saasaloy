import { BASE_INTENT, BASE_MODULE } from "./base.js";
import { toDiff } from "./patch/diff.js";
import type { UpdateNoteText } from "./update-notes.js";
import type {
  ModuleUpdatePlan,
  PlannedUpdateFile,
  PlannedUpdatePatch,
  UpdatePlan,
} from "./updater.js";

// The artifact the whole feature exists for (build spec §2.9, CONTEXT.md): for every
// file `update` refused to overwrite, a structured, agent-consumable merge plan —
// natural-language intent + target files + old/new context — that can be handed
// straight to an agent CLI with no editing. Markdown, because it is the one format
// both a person and an agent read without a renderer (issue #48).
//
// Pure string building: it writes nothing and reads nothing. The command decides
// whether the result goes to stdout or to `--out`.

/**
 * Render the merge plan for everything that drifted and every update note the run
 * selected, or `""` when there is neither.
 */
export function renderMergePlan(plan: UpdatePlan): string {
  const modules = plan.modules.filter((m) => m.needsMerge);
  const noteCount = plan.notes.length + plan.mayApplyNotes.length;
  if (modules.length === 0 && noteCount === 0) {
    return "";
  }

  const fileCount = modules.reduce(
    (total, m) =>
      total +
      m.files.filter(isMergeFile).length +
      m.removals.filter(isMergeFile).length,
    0
  );

  const notesLine =
    noteCount === 0
      ? ""
      : ` This update also carries ${countLabel(noteCount, "update note")}: work outside ` +
        "the files Saasaloy writes. They come first, below.";
  const out: string[] = [
    "# Saasaloy merge plan",
    "",
    modules.length === 0
      ? `Generated by \`saasaloy update\`. No file needs a merge. This update carries ` +
        `${countLabel(noteCount, "update note")}: work outside the files Saasaloy writes. ` +
        "Work through each one below."
      : `Generated by \`saasaloy update\`. ${countLabel(fileCount, "file")} across ` +
        `${countLabel(modules.length, "module")} changed on both sides — upstream and here — so ` +
        "the update stopped short of writing them. Saasaloy never overwrites work you did by " +
        `hand; below is everything needed to reconcile the two sets of changes.${notesLine}`,
    "",
  ];

  if (noteCount > 0) {
    out.push(...renderUpdateNotes(plan));
  }
  for (const mod of modules) {
    out.push(...renderModule(mod));
  }

  if (modules.length > 0) {
    out.push(...renderInstructions(plan));
  }
  out.push(...renderVerification(plan, modules.length > 0));
  return `${out.join("\n").trimEnd()}\n`;
}

/**
 * The "Update notes" section (#298): each note's id, title and body, the body's headings
 * demoted to nest under the note's own. Notes the run could not place get a subsection
 * of their own that asks the agent to check each one first.
 */
function renderUpdateNotes(plan: UpdatePlan): string[] {
  const out: string[] = [
    "## Update notes",
    "",
    "Each note is work this update asks of the project outside the files Saasaloy writes: an " +
      "import path in your own code, a moved block, a setting. Work through them in order. A " +
      "note says what `update` already did, what this merge plan holds for it, what you do, " +
      "and how to check the result.",
    "",
  ];
  for (const note of plan.notes) {
    out.push(...renderNote(note, 3));
  }
  if (plan.mayApplyNotes.length > 0) {
    out.push(
      "### Notes that may apply",
      "",
      "Saasaloy cannot tell whether the project already took these notes. Either the module " +
        "had no earlier version to compare against, or the base was adopted and nothing " +
        "records the CLI that made it. Check whether each note applies before you act on it: " +
        "if the project already holds what its steps produce, skip it.",
      ""
    );
    for (const note of plan.mayApplyNotes) {
      out.push(...renderNote(note, 4));
    }
  }
  out.push(
    "### When a note is done",
    "",
    "Saasaloy records each note above as pending, prints it in every later merge plan, and " +
      "`saasaloy update` exits `3` until it is cleared. When a note's work is done and its " +
      "Verify step passes, or a note that may apply does not apply, record it:",
    "",
    ...fenced(doneCommand(plan), "sh"),
    "Pass `--done` once for each finished note, with the id from its heading. An id that is " +
      "not pending refuses the run. `update` refuses a working tree with uncommitted changes, " +
      "so commit the work first or add `--force`.",
    ""
  );
  return out;
}

/** The command that records every note of this plan as done (#298), one `--done` per id. */
function doneCommand(plan: UpdatePlan): string {
  const flags = [...plan.notes, ...plan.mayApplyNotes].map(
    (note) => ` \\\n  --done ${note.id}`
  );
  return `saasaloy update${flags.join("")} --yes\n`;
}

function renderNote(note: UpdateNoteText, level: number): string[] {
  return [
    `${"#".repeat(level)} ${note.id}: ${note.title}`,
    "",
    ...demoteHeadings(note.body, level + 1)
      .trimEnd()
      .split("\n"),
    "",
  ];
}

/**
 * Shift every ATX heading outside a fenced block so the body's highest heading lands at
 * `top`, capped at `######`. A fenced block's lines are content, never headings.
 */
function demoteHeadings(body: string, top: number): string {
  const lines = body.split("\n");
  const headings: (number | undefined)[] = [];
  let fence: string | undefined;
  for (const line of lines) {
    const marker = /^ {0,3}(`{3,}|~{3,})/.exec(line)?.[1];
    if (marker !== undefined) {
      if (fence === undefined) {
        fence = marker;
      } else if (
        marker.startsWith(fence[0]!) &&
        marker.length >= fence.length
      ) {
        fence = undefined;
      }
      headings.push(undefined);
      continue;
    }
    headings.push(
      fence === undefined ? /^(#{1,6})[ \t]/.exec(line)?.[1]?.length : undefined
    );
  }
  const levels = headings.filter((h): h is number => h !== undefined);
  if (levels.length === 0) {
    return body;
  }
  const shift = Math.max(0, top - Math.min(...levels));
  return lines
    .map((line, index) => {
      const level = headings[index];
      return level === undefined
        ? line
        : `${"#".repeat(Math.min(6, level + shift))}${line.slice(level)}`;
    })
    .join("\n");
}

/** Only the states that actually need a human or an agent — the merge plan's whole subject. */
function isMergeFile(file: PlannedUpdateFile): boolean {
  return (
    file.action === "drift" ||
    file.action === "conflict" ||
    file.action === "delete-drift"
  );
}

function countLabel(n: number, noun: string): string {
  return `${n} ${noun}${n === 1 ? "" : "s"}`;
}

function renderModule(mod: ModuleUpdatePlan): string[] {
  const out: string[] = [`## ${mod.name}`, "", "### Intent", ""];

  if (mod.baseRecord) {
    // The base has no commit range to read subjects from: the template ships inside the
    // CLI. One line says what the agent needs to know (#120).
    out.push(
      `The base template shipped with a newer CLI. For every file below: ${BASE_INTENT}.`
    );
  } else if (mod.intent.length > 0) {
    out.push(
      "What changed upstream, from the commits touching this module:",
      ""
    );
    for (const subject of mod.intent) {
      out.push(`- ${subject}`);
    }
  } else {
    out.push(
      `No commit subjects could be read for this range${
        mod.noMergeBase ? ` (${mod.noMergeBase})` : ""
      } — read the diffs below to infer what the module intended.`
    );
  }
  out.push("", "### Provenance", "");
  if (mod.baseRecord) {
    out.push(
      `- Module: \`${mod.name}\` (the template \`saasaloy init\` rendered)`,
      `- Source: \`${mod.comparison.source}\``,
      `- Recorded (your version): \`${mod.comparison.current}\` — CLI version, then template hash`,
      `- Running (new version): \`${mod.comparison.latest}\``
    );
  } else {
    out.push(
      `- Module: \`${mod.name}\``,
      `- Source: \`${mod.comparison.source}\``,
      `- Ref: \`${mod.comparison.ref}\``,
      `- Base (your version): \`${mod.comparison.current}\``,
      `- Theirs (new version): \`${mod.comparison.latest}\``
    );
  }
  if (mod.noMergeBase) {
    out.push(
      `- **no merge base — ${mod.noMergeBase}**: the original file can't be refetched, so the ` +
        "diffs below are two-way (theirs vs. yours) and you must judge which side each " +
        "difference came from."
    );
  }
  out.push("");

  const mergeFiles = mod.files.filter(isMergeFile);
  const droppedFiles = mod.removals.filter(isMergeFile);
  if (mergeFiles.length > 0 || droppedFiles.length > 0) {
    out.push("### Files to merge", "");
    for (const file of mergeFiles) {
      out.push(...renderFile(file));
    }
    for (const file of droppedFiles) {
      out.push(...renderDroppedFile(file));
    }
  }

  const movedPatches = mod.patches.filter((p) => p.matched !== undefined);
  if (movedPatches.length > 0) {
    out.push(
      "### Config patches that moved",
      "",
      "These config edits were skipped: the key the module identifies its entry by is already " +
        "present, holding a value that isn't the one the new version declares. That is almost " +
        "always a setting you changed on purpose, so nothing was written.",
      ""
    );
    for (const patch of movedPatches) {
      out.push(...renderPatch(patch));
    }
  }

  return out;
}

const ACTION_HEADING: Record<string, string> = {
  drift: "you edited this file after it was applied",
  conflict: "new file collides with yours",
  "delete-drift": "the module dropped this file",
};

function renderFile(file: PlannedUpdateFile): string[] {
  const out: string[] = [
    `#### \`${file.target}\``,
    "",
    `Source in the ${file.module === BASE_MODULE ? "template" : "module"}: \`${file.from}\` — ${ACTION_HEADING[file.action] ?? file.action}.`,
    "",
  ];

  if (file.action === "conflict") {
    out.push(
      file.base === undefined
        ? "The new version of the module ships this file, but a file already sits at that path " +
            "that Saasaloy never wrote. There is no base for it — the module didn't have it at " +
            "your current version — so this is a two-way comparison."
        : "The new version of the module ships this file, but a file already sits at that path " +
            "that Saasaloy never wrote, so nothing records what it looked like when it was " +
            "applied. The module's own older version of the file is available and is used as " +
            "the base below — but the on-disk file was never tracked against it, so treat it as " +
            "independent work rather than as edits on top of that base.",
      ""
    );
  }

  if (file.projectOwned) {
    out.push(
      "This file is yours: the template ships it once and never writes it again. The " +
        "template's copy moved, so the change is shown below for you to take what you want " +
        "from it. Nothing here was written.",
      ""
    );
  } else if (file.merged) {
    out.push(
      "This file was merged before (`saasaloy update --resolved`), so it holds edits Saasaloy " +
        "did not write. The module moved again since that merge, and the file was left alone.",
      ""
    );
  } else if (file.adopted) {
    out.push(
      "Saasaloy adopted this file rather than writing it, so the hash it records came off " +
        "your disk and proves nothing about who wrote these bytes. It is treated as edited " +
        "and was left alone.",
      ""
    );
  }

  if (file.patchedBy && file.patchedBy.length > 0) {
    out.push(
      `Note: \`${file.patchedBy.join("`, `")}\` also applied a config patch to this file. Part of ` +
        "the difference below is that patch rather than an edit anyone made by hand — keep those " +
        "lines when you merge.",
      ""
    );
  }

  const base = file.base;
  const theirs = file.theirs ?? "";
  const mine = file.mine ?? "";

  if (base === undefined) {
    out.push(
      "**theirs → mine** (no base available — two-way):",
      "",
      ...fenced(toDiff(theirs, mine, file.target), "diff")
    );
  } else {
    out.push(
      "**base → theirs** (what the module changed):",
      "",
      ...fenced(toDiff(base, theirs, file.target), "diff"),
      "**base → mine** (what you changed):",
      "",
      ...fenced(toDiff(base, mine, file.target), "diff")
    );
  }
  return out;
}

function renderDroppedFile(file: PlannedUpdateFile): string[] {
  const out: string[] = [
    `#### \`${file.target}\``,
    "",
    `Source in the module: \`${file.from}\`. The new version of the module dropped this file, ` +
      "but you had edited it — so it was left exactly as it is and is now yours alone " +
      "(Saasaloy no longer tracks it). Your edits are still here; decide whether the work " +
      "they represent still belongs in the project now the module no longer ships it.",
    "",
  ];
  if (file.base !== undefined && file.mine !== undefined) {
    out.push(
      "**base → mine** (what you changed before it was dropped):",
      "",
      ...fenced(toDiff(file.base, file.mine, file.target), "diff")
    );
  }
  return out;
}

function renderPatch(patch: PlannedUpdatePatch): string[] {
  const matched = patch.matched;
  if (!matched) {
    return [];
  }
  return [
    `#### \`${patch.file}\` — \`${patch.patch.kind}\``,
    "",
    `- Identity: \`${matched.key}\``,
    `- On disk: \`${JSON.stringify(matched.current)}\``,
    `- The new version declares: \`${JSON.stringify(matched.wanted)}\``,
    "",
    "Reconcile these by hand if the new value matters; keep yours if it was deliberate.",
    "",
  ];
}

/**
 * Where the lock is left, said concretely when every merging module shares one base SHA
 * and generically when a bare `update` collected several.
 */
function lockStaysOn(plan: UpdatePlan): string {
  const bases = [
    ...new Set(
      plan.modules.filter((m) => m.needsMerge).map((m) => m.comparison.current)
    ),
  ];
  return bases.length === 1
    ? `the lock stays on \`${bases[0]}\``
    : "each module's lock entry stays on the base SHA named in its Provenance section";
}

/**
 * The command that records every file of this plan as merged (#223): one `--resolved`
 * per file, in the order the plan lists them, then `--yes`, because an agent has no
 * terminal to confirm in.
 */
function resolveCommand(plan: UpdatePlan): string {
  const targets = plan.modules
    .flatMap((m) => (m.needsMerge ? [...m.files, ...m.removals] : []))
    .filter(isMergeFile)
    .map((file) => file.target);
  const flags = targets.map(
    (target) => ` \\\n  --resolved ${shellQuote(target)}`
  );
  return `saasaloy update${flags.join("")} --yes\n`;
}

/** Quote a path for a POSIX shell only when it needs it. */
function shellQuote(path: string): string {
  return /^[\w@%+=:,./-]+$/.test(path)
    ? path
    : `'${path.replaceAll("'", "'\\''")}'`;
}

function renderInstructions(plan: UpdatePlan): string[] {
  return [
    "## Instructions",
    "",
    "You are reconciling two sets of changes to the same files: the module's (base → theirs) " +
      "and the user's (base → mine). Work file by file.",
    "",
    "1. Read the intent above to understand what the module was trying to fix or add.",
    "2. For each file, apply the module's change to the file **as it currently stands on disk** " +
      "— the on-disk copy is `mine` and it is the version to edit.",
    "3. **The user's edits must not be lost.** Where the two changes touch the same lines, keep " +
      "the user's intent and re-express the module's fix on top of it. If the two genuinely " +
      "conflict and you cannot preserve both, leave the user's version in place and say so " +
      "rather than choosing for them.",
    "4. Don't touch files that aren't listed here — everything else was already updated cleanly.",
    "5. Don't edit `.saasaloy/manifest.json` or `saasaloy-lock.json` — Saasaloy owns both. " +
      "Once the files are merged, record them with `saasaloy update --resolved`, below.",
    "",
    "### What Saasaloy records afterwards",
    "",
    "Nothing until you say a merge is done. Saasaloy has no way to tell a finished merge from " +
      "an unfinished one, so until then the files above stay tracked at the module's old " +
      `version and ${lockStaysOn(plan)}, and a later \`saasaloy update\` will offer the same ` +
      "files again, against the same base.",
    "",
    "When the files are merged, record them:",
    "",
    ...fenced(resolveCommand(plan), "sh"),
    "Pass `--resolved` once for each file you merged, with the path from its heading above. " +
      "Saasaloy records each file's current hash as its new baseline without checking what it " +
      "holds, so record a file only once its merge is finished. Once nothing else of a module " +
      "waits on a merge, its lock moves to the new version, and the next `saasaloy update` " +
      'stops offering those files. A config patch under "Config patches that moved" is not a ' +
      "file: reconcile it by hand, and the module's lock stays where it is. `update` refuses a " +
      "working tree with uncommitted changes, so commit the merge first or add `--force`.",
    "",
  ];
}

function renderVerification(plan: UpdatePlan, merging: boolean): string[] {
  const out: string[] = [
    "## Verification",
    "",
    merging
      ? "Run these after merging — `saasaloy update` deliberately runs nothing itself:"
      : "Run these once the notes are done. `saasaloy update` runs nothing itself:",
    "",
    `- \`${plan.verifyCommand}\``,
  ];
  if (plan.migrationCommand) {
    out.push(
      `- \`${plan.migrationCommand}\` — the update changed the database schema`
    );
  }
  out.push("");
  return out;
}

/**
 * Wrap content in a fence long enough to survive whatever it contains — a merge plan
 * routinely carries markdown files that hold their own code fences, and a three-backtick
 * fence would end the block early and corrupt the document an agent reads.
 */
function fenced(content: string, language: string): string[] {
  let longest = 0;
  for (const match of content.matchAll(/`{3,}/g)) {
    longest = Math.max(longest, match[0].length);
  }
  const fence = "`".repeat(Math.max(3, longest + 1));
  return [`${fence}${language}`, content.replace(/\n$/, ""), fence, ""];
}
